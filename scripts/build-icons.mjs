// Copies only the icons the app uses (renderer/icons/iconNames.js) from @hugeicons/core-free-icons
// (the agents' logos from @lobehub/icons-static-svg and the technologies' logos from simple-icons)
// into renderer/icons/hugeicons.js. The full package is ~150 MB, so it stays a dev dependency and
// neither the installers nor the web build carry it. Run with `npm run icons`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ICON_NAMES, BRAND_NAMES, STACK_LOGOS } from '../renderer/icons/iconNames.js';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'node_modules', '@hugeicons', 'core-free-icons', 'dist', 'esm');
const target = path.join(root, 'renderer', 'icons', 'hugeicons.js');

const icons = {};
for (const [name, exportName] of Object.entries(ICON_NAMES)) {
  const file = path.join(source, `${exportName}.js`);
  if (!fs.existsSync(file)) throw new Error(`Hugeicons has no ${exportName} (icon "${name}")`);
  const { default: nodes } = await import(file);
  // [tag, attrs] pairs; React's `key` is dropped
  icons[name] = nodes.map(([tag, { key, ...attrs }]) => [tag, attrs]);
}

const header = '// Generated by scripts/build-icons.mjs from @hugeicons/core-free-icons (MIT). Do not edit.\n';
fs.writeFileSync(target, `${header}export const ICONS = ${JSON.stringify(icons, null, 1)};\n`);
console.log(`${Object.keys(icons).length} icons -> ${path.relative(root, target)}`);

// The agents' logos (renderer/icons/brands.js): the SVG as it comes, without its size and title, with
// its gradient ids made unique per logo so two logos on screen never mix colors
const brandSource = path.join(root, 'node_modules', '@lobehub', 'icons-static-svg', 'icons');
const brands = {};
for (const [name, file] of Object.entries(BRAND_NAMES)) {
  const full = path.join(brandSource, `${file}.svg`);
  if (!fs.existsSync(full)) throw new Error(`@lobehub/icons-static-svg has no ${file}.svg (logo "${name}")`);
  let svg = fs.readFileSync(full, 'utf8').trim()
    .replace(/<title>.*?<\/title>/, '')
    .replace(/\s(width|height|style)="[^"]*"/g, '')
    .replace('<svg ', '<svg class="icon agent-logo" aria-hidden="true" ');
  for (const [, id] of svg.matchAll(/id="([^"]+)"/g)) svg = svg.replaceAll(`"${id}"`, `"${name}-${id}"`).replaceAll(`#${id})`, `#${name}-${id})`);
  brands[name] = svg;
}
// The technologies' logos (simple-icons, CC0): one path each, filled with the text color
const stackSource = path.join(root, 'node_modules', 'simple-icons', 'icons');
for (const [name, file] of Object.entries(STACK_LOGOS)) {
  const full = path.join(stackSource, `${file}.svg`);
  if (!fs.existsSync(full)) throw new Error(`simple-icons has no ${file}.svg (logo "${name}")`);
  brands[name] = fs.readFileSync(full, 'utf8').trim()
    .replace(/<title>.*?<\/title>/, '')
    .replace(/\s(role|xmlns)="[^"]*"/g, '')
    .replace('<svg ', '<svg class="icon stack-logo" fill="currentColor" aria-hidden="true" ');
}
const brandTarget = path.join(root, 'renderer', 'icons', 'brands.js');
fs.writeFileSync(brandTarget, `// Generated by scripts/build-icons.mjs from @lobehub/icons-static-svg (MIT) and simple-icons (CC0). Do not edit.\nexport const BRANDS = ${JSON.stringify(brands, null, 1)};\n`);
console.log(`${Object.keys(brands).length} logos -> ${path.relative(root, brandTarget)}`);
